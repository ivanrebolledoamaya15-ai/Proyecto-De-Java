    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblInforme.getModel();
        modelo.setRowCount(0);
        try {
            int posicion = 1;
            for (Object[] f : baseDatos.consultar("SELECT equipo, pj, pg, pe, pp, gf, gc, gf - gc AS dg, puntos FROM vista_posiciones ORDER BY puntos DESC, dg DESC, gf DESC")) {
                modelo.addRow(new Object[]{posicion, f[0], f[1], f[2], f[3], f[4], f[5], f[6], f[7], f[8]});
                posicion++;
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo leer la base de datos: " + ex.getMessage());
        }
    }

