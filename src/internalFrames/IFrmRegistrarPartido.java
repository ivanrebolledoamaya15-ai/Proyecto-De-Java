    private void cargarEquipos() {
        cmbLocal.removeAllItems();
        cmbVisitante.removeAllItems();
        try {
            equipos = baseDatos.listarEquipos();
            for (Object[] e : equipos) {
                cmbLocal.addItem((String) e[1]);
                cmbVisitante.addItem((String) e[1]);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo leer la base de datos: " + ex.getMessage());
        }
    }

    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblPartidos.getModel();
        modelo.setRowCount(0);
        try {
            for (Object[] fila : baseDatos.consultar("SELECT local, visitante, fecha, marcador FROM vista_partidos ORDER BY fecha")) {
                modelo.addRow(fila);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo leer la base de datos: " + ex.getMessage());
        }
    }

    private boolean esNumeroEntero(String texto) {
        try {
            Integer.parseInt(texto);
            return true;
        } catch (NumberFormatException e) {
            return false;
        }
    }

    private boolean fechaValida(String f) {
        if (f.length() != 10 || f.charAt(2) != '/' || f.charAt(5) != '/') {
            return false;
        }
        try {
            int dia = Integer.parseInt(f.substring(0, 2));
            int mes = Integer.parseInt(f.substring(3, 5));
            int anio = Integer.parseInt(f.substring(6));
            return dia >= 1 && dia <= 31 && mes >= 1 && mes <= 12 && anio >= 1900;
        } catch (NumberFormatException e) {
            return false;
        }
    }

