    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblInforme.getModel();
        modelo.setRowCount(0);
        try {
            for (Object[] fila : baseDatos.consultar("SELECT equipo, entrenador, cantidad_jugadores FROM vista_equipos")) {
                modelo.addRow(fila);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo leer la base de datos: " + ex.getMessage());
        }
    }

