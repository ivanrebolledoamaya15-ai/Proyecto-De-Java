    private void crearMenus() {
        javax.swing.JMenu menuTorneo = new javax.swing.JMenu("Torneo");

        MenuRegistrarJugador = new javax.swing.JMenuItem("Registrar jugador");
        MenuRegistrarJugador.addActionListener(this::MenuRegistrarJugadorActionPerformed);
        menuTorneo.add(MenuRegistrarJugador);

        MenuRegistrarPartido = new javax.swing.JMenuItem("Registrar partido");
        MenuRegistrarPartido.addActionListener(this::MenuRegistrarPartidoActionPerformed);
        menuTorneo.add(MenuRegistrarPartido);

        MenuRegistrarGoles = new javax.swing.JMenuItem("Registrar goles");
        MenuRegistrarGoles.addActionListener(this::MenuRegistrarGolesActionPerformed);
        menuTorneo.add(MenuRegistrarGoles);

        javax.swing.JMenu menuInformes = new javax.swing.JMenu("Informes");

        MenuInformeEquipos = new javax.swing.JMenuItem("Equipos inscritos");
        MenuInformeEquipos.addActionListener(this::MenuInformeEquiposActionPerformed);
        menuInformes.add(MenuInformeEquipos);

        MenuTablaPosiciones = new javax.swing.JMenuItem("Tabla de posiciones");
        MenuTablaPosiciones.addActionListener(this::MenuTablaPosicionesActionPerformed);
        menuInformes.add(MenuTablaPosiciones);

        MenuInformePartidos = new javax.swing.JMenuItem("Partidos");
        MenuInformePartidos.addActionListener(this::MenuInformePartidosActionPerformed);
        menuInformes.add(MenuInformePartidos);

        MenuInformeGoleadores = new javax.swing.JMenuItem("Goleadores");
        MenuInformeGoleadores.addActionListener(this::MenuInformeGoleadoresActionPerformed);
        menuInformes.add(MenuInformeGoleadores);

        jMenuBar1.add(menuTorneo);
        jMenuBar1.add(menuInformes);

        if (this.idRol != 1) {
            MenuRegistrarJugador.setEnabled(false);
            MenuRegistrarPartido.setEnabled(false);
            MenuRegistrarGoles.setEnabled(false);
        }
    }

