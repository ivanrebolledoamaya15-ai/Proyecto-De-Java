    private void cargarEquipos() {
        cmbEquipo.removeAllItems();
        try {
            equipos = baseDatos.listarEquipos();
            for (Object[] e : equipos) {
                cmbEquipo.addItem((String) e[1]);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo leer la base de datos: " + ex.getMessage());
        }
    }

    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblJugadores.getModel();
        modelo.setRowCount(0);
        int pos = cmbEquipo.getSelectedIndex();
        if (pos < 0) {
            return;
        }
        int idEquipo = (Integer) equipos.get(pos)[0];
        try {
            for (Object[] j : baseDatos.listarJugadores(idEquipo)) {
                modelo.addRow(new Object[]{j[0], j[1], j[2], j[3]});
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo leer la base de datos: " + ex.getMessage());
        }
    }

    private boolean esNumeroEntero(String texto) {
        try {
            Integer.parseInt(texto);
            return true;
        } catch (NumberFormatException e) {
            return false;
        }
    }

