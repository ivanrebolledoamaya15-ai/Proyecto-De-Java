    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        if (equipos.size() < 2) {
            JOptionPane.showMessageDialog(this, "Debe haber al menos dos equipos registrados");
            return;
        }

        int posLocal = cmbLocal.getSelectedIndex();
        int posVisitante = cmbVisitante.getSelectedIndex();
        String fecha = txtFecha.getText().trim();
        String golesLocalTexto = txtGolesLocal.getText().trim();
        String golesVisitanteTexto = txtGolesVisitante.getText().trim();

        if (fecha.isEmpty() || golesLocalTexto.isEmpty() || golesVisitanteTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos tienen que estar llenos");
            return;
        }

        if (posLocal == posVisitante) {
            JOptionPane.showMessageDialog(this, "El equipo local y el visitante deben ser diferentes");
            return;
        }

        if (!fechaValida(fecha)) {
            JOptionPane.showMessageDialog(this, "La fecha debe tener el formato dd/mm/aaaa");
            return;
        }

        if (!esNumeroEntero(golesLocalTexto) || Integer.parseInt(golesLocalTexto) < 0
                || !esNumeroEntero(golesVisitanteTexto) || Integer.parseInt(golesVisitanteTexto) < 0) {
            JOptionPane.showMessageDialog(this, "Los goles deben ser números enteros válidos");
            return;
        }

        int idLocal = (Integer) equipos.get(posLocal)[0];
        int idVisitante = (Integer) equipos.get(posVisitante)[0];
        int golesLocal = Integer.parseInt(golesLocalTexto);
        int golesVisitante = Integer.parseInt(golesVisitanteTexto);
        String fechaSql = fecha.substring(6) + "-" + fecha.substring(3, 5) + "-" + fecha.substring(0, 2);

        try {
            baseDatos.registrarPartido(idLocal, idVisitante, fechaSql, golesLocal, golesVisitante);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el partido: " + ex.getMessage());
            return;
        }

        cargarTabla();
        limpiar();
    }//GEN-LAST:event_btnRegistrarActionPerformed

