    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        int posJugador = cmbJugador.getSelectedIndex();
        String golesTexto = txtGoles.getText().trim();

        if (posJugador < 0) {
            JOptionPane.showMessageDialog(this, "Debe haber un equipo con jugadores registrados");
            return;
        }

        if (golesTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos tienen que estar llenos");
            return;
        }

        if (!esNumeroEntero(golesTexto) || Integer.parseInt(golesTexto) <= 0) {
            JOptionPane.showMessageDialog(this, "Los goles deben ser un número entero mayor que 0");
            return;
        }

        int idJugador = (Integer) jugadores.get(posJugador)[0];

        try {
            baseDatos.registrarGoles(idJugador, Integer.parseInt(golesTexto));
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo registrar los goles: " + ex.getMessage());
            return;
        }

        cargarJugadores();
        cmbJugador.setSelectedIndex(posJugador);
        txtGoles.setText("");
    }//GEN-LAST:event_btnAgregarActionPerformed

