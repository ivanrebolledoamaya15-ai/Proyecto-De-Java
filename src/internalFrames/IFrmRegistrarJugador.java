    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        int pos = cmbEquipo.getSelectedIndex();
        if (pos < 0) {
            JOptionPane.showMessageDialog(this, "Primero debe registrar un equipo");
            return;
        }

        String nombre = txtNombre.getText().trim();
        String edadTexto = txtEdad.getText().trim();
        String posicion = txtPosicion.getText().trim();

        if (nombre.isEmpty() || edadTexto.isEmpty() || posicion.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos tienen que estar llenos");
            return;
        }

        if (!esNumeroEntero(edadTexto) || Integer.parseInt(edadTexto) <= 0) {
            JOptionPane.showMessageDialog(this, "La edad debe ser un número entero válido");
            return;
        }

        int idEquipo = (Integer) equipos.get(pos)[0];
        int edad = Integer.parseInt(edadTexto);

        try {
            if (baseDatos.existeJugador(idEquipo, nombre)) {
                JOptionPane.showMessageDialog(this, "Ya existe un jugador con ese nombre en este equipo");
                return;
            }
            baseDatos.registrarJugador(nombre, edad, posicion, idEquipo);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el jugador: " + ex.getMessage());
            return;
        }

        cargarTabla();
        limpiar();
    }//GEN-LAST:event_btnAgregarActionPerformed

